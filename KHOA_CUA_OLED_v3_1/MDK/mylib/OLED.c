// In chuoi tai vi tri hien tai: moi ky tu 5 cot font + 1 cot trong
static void oled_print(char i2c, char str[])
{
    int i = 0, j;
    char c;

    oled_data_begin(i2c);
    while (str[i]) {
        c = str[i];
        if (c < 32 || c > 127) c = '?';          // ky tu ngoai bang font -> in dau ?
        for (j = 0; j < 5; j++) {
            i2c_data(i2c, ASCII[c - 32][j]);
        }
        i2c_data(i2c, 0x00);                     // cot trong giua 2 ky tu
        i++;
    }
    i2c_stop(i2c);
}

// In chuoi tai page Ypos (0..7), cot Xpos (0..127)
void oled_msg(char i2c, uint8_t Ypos, uint8_t Xpos, char str[])
{
    oled_pos_raw(i2c, Ypos, Xpos + OLED_COL_OFFSET);
    oled_print(i2c, str);
}
