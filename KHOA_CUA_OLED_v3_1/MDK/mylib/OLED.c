#include "OLED.h"
#include "i2c.h"

#define i2c_FM   0x2d     // toc do (i2c.c cho I2C1 tu dung 100kHz, tham so nay chi dung cho I2C2)
#define OLED_ADDR 0x78    // dia chi OLED (0x3C << 1)

/* ----- Gui lenh ----- */

// Gui lenh 1 byte (byte dieu khien 0x00 = "cac byte sau la LENH")
static void oled_cmd_1byte(char i2c, char data)
{
    i2c_start(i2c);
    i2c_add(i2c, OLED_ADDR, 0);
    i2c_data(i2c, 0x00);
    i2c_data(i2c, data);
    i2c_stop(i2c);
}

// Gui lenh 2 byte
static void oled_cmd_2byte(char i2c, char data[])
{
    int i;
    i2c_start(i2c);
    i2c_add(i2c, OLED_ADDR, 0);
    i2c_data(i2c, 0x00);
    for (i = 0; i < 2; i++) {
        i2c_data(i2c, data[i]);
    }
    i2c_stop(i2c);
}

/* ----- Khoi tao (giu nguyen day lenh cua thu vien goc) ----- */
static char cmd[]  = {0xA8, 0x3F};
static char cmd1[] = {0xD3, 0x00};
static char cmd2[] = {0xDA, 0x12};
static char cmd3[] = {0x81, 0x7F};
static char cmd4[] = {0xD5, 0x80};
static char cmd5[] = {0x8D, 0x14};
static char cmd6[] = {0x20, 0x10};

void oled_init(char i2c)
{
    i2c_init(i2c, i2c_FM);
    oled_cmd_2byte(i2c, cmd);
    oled_cmd_2byte(i2c, cmd1);

    oled_cmd_1byte(i2c, 0x40);
    oled_cmd_1byte(i2c, 0xA1);

    oled_cmd_1byte(i2c, 0xC8);

    oled_cmd_2byte(i2c, cmd2);

    oled_cmd_2byte(i2c, cmd3);

    oled_cmd_1byte(i2c, 0xA4);
    oled_cmd_1byte(i2c, 0xA6);

    oled_cmd_2byte(i2c, cmd4);

    oled_cmd_2byte(i2c, cmd5);

    oled_cmd_1byte(i2c, 0xAF);

    oled_cmd_2byte(i2c, cmd6);
}

/* ----- Dat vi tri ghi ----- */

// Dat con tro ghi: page (0..7) va cot THUC cua RAM (khong cong offset)
static void oled_pos_raw(char i2c, uint8_t page, uint8_t col)
{
    oled_cmd_1byte(i2c, 0x00 + (0x0F & col));          // 4 bit thap cua cot
    oled_cmd_1byte(i2c, 0x10 + (0x0F & (col >> 4)));   // 4 bit cao cua cot
    oled_cmd_1byte(i2c, 0xB0 + page);                  // chon page
}

/* ----- Ve chu / xoa man hinh (gui nhieu byte trong 1 lan I2C cho nhanh) ----- */

// Bat dau gui DU LIEU hien thi (byte dieu khien 0x40 = "cac byte sau la DU LIEU")
static void oled_data_begin(char i2c)
{
    i2c_start(i2c);
    i2c_add(i2c, OLED_ADDR, 0);
    i2c_data(i2c, 0x40);
}

// Xoa sach: moi page ghi 132 cot 0x00 (du cho ca SH1106 132 cot lan SSD1306 128 cot)
void oled_blank(char i2c)
{
    uint8_t page, col;

    for (page = 0; page < 8; page++) {
        oled_pos_raw(i2c, page, 0);
        oled_data_begin(i2c);
        for (col = 0; col < 132; col++) {
            i2c_data(i2c, 0x00);
        }
        i2c_stop(i2c);
    }
    oled_pos_raw(i2c, 0, 0);
}

